/** 그 자리·그 점수·그 시도의 답변. 은행에 없으면 `null`(호출부가 접는다) */
export function bankAnswer(
  problemNo: number,
  axisCode: AxisCode,
  hintsUsed: number,
  score: Score,
): string | null {
  const axis = ANSWER_BANK[`${problemNo}-${axisCode}`]
  if (!axis) return null
  if (score >= 3) return axis.pass[score as 3 | 4 | 5] ?? null
  return axis.fail[score as 0 | 1 | 2]?.[hintsUsed] ?? null
}
