/*
  폼 입력 검증에 쓰는 순수 값 — 도메인을 모른다(`lib/format.ts`와 같은 판단).

  같은 정규식이 이름만 다른 채 5곳에 흩어져 있었다(`EMAIL_PATTERN`·`EMAIL_SHAPE`·`EMAIL_RE`).
  문구도 각자 적혀 있어 한 곳만 고치면 나머지가 조용히 갈린다. **두 번째 도메인이 필요로 한
  시점에 올린다**는 규칙에 이미 한참 전에 도달해 있었다.

  ## 형식만 본다 — 이 주소가 실재하는지는 서버가 판정한다
  "이미 등록된 이메일"·"기관 도메인이 아님"은 **클라이언트가 원리적으로 알 수 없다.**
  여기서 거르는 것은 왕복 없이 즉시 알려줄 수 있는 것뿐이고, 나머지는 서버 응답의
  `fieldErrors`로 온다. 두 층은 대체 관계가 아니라 보는 것이 다르다.
*/

/**
 * 이메일 형식 — **명백히 주소가 아닌 것**만 거른다.
 *
 * RFC를 온전히 구현하지 않는다. 엄격한 정규식은 유효한 주소를 거절하는 쪽으로 틀리고,
 * 그 실패는 사용자가 **자기 주소를 못 쓰는** 형태로 나타나 훨씬 나쁘다.
 */
export const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/

/** 화면 문구도 한 곳에서 — 같은 실패에 다른 문장이 뜨면 사용자는 다른 문제로 읽는다 */
export const EMAIL_INVALID_MESSAGE = '올바른 이메일 형식이 아닙니다.'

export const isEmailShape = (value: string) => EMAIL_PATTERN.test(value)
