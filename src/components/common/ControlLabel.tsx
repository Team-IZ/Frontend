/*
  툴바 컨트롤 **안에** 들어가는 이름표. 값과는 얇은 세로선으로 가른다.

  ```
  ┌──────────────────────┐
  │ 상태 │ 전체 (7)    ▾ │
  └──────────────────────┘
     ↑      ↑
   이름표  고른 값
  ```

  ▸ **이름표는 컨트롤 안에 있다.** 밖에 두면 컨트롤마다 앞에 붙는 글자 폭이 달라
    셀렉트들이 안 맞고, 무엇보다 라벨과 컨트롤이 **다른 것**처럼 보인다.
  ▸ **이름표와 값은 크기가 같고 색만 다르다.** 이름표를 작게 하면 한 컨트롤 안에
    글자 크기가 둘이 되어 값이 어디서 시작하는지 눈이 한 번 더 찾는다.
  ▸ **감싸는 쪽이 색을 정하지 않는다.** 바깥 span에 `text-fg-subtle`을 두면 값까지
    회색으로 상속된다 — 실제로 OP-02에서 회차만 회색이던 원인이었다.

  한때 `라벨 · 값` 문자열이었다(`정렬 · 준비 필요 순`). 값에 점이 들어간 이름이 오면
  어디까지가 이름표인지 읽을 수 없고, 드롭다운 항목마다 같은 접두사가 반복됐다.
*/
export default function ControlLabel({ children }: { children: React.ReactNode }) {
  return <span className="text-fg-subtle border-border mr-1 border-r pr-2.5">{children}</span>
}
