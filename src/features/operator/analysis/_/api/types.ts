/*
  OP-02 분석 **계약** — 서버와 주고받는 모양만 둔다(api-boundary §1-③).

  이 화면의 고유 질문은 하나다 — *"우리가 나아지고 있나."* OP-01은 **지금**만 본다.
  나머지 질문은 전부 다른 화면이 답하므로, 여기 있는 것은 **무엇과 견줘야만 읽히는 값**뿐이다.

  타입에 박혀 있는 전제 셋:
    · **미프끼리는 값을 비교할 수 없다.** 회차마다 개념·코드·난이도가 다르다(6-3) —
      `19%`가 `12%`보다 나쁜 것인지 그 회차가 어려웠던 것인지 값만으로는 안 갈린다.
      그래서 셀이 **값 + 기수 대비 부호**를 같이 갖는다.
    · **판정은 리포트 발행 시점에 켜진다**(9-2 · 10-2 일괄 발행). 미발행 회차는 값이
      아니라 **상태**다 — `집계 전`과 `시작 전`과 `0%`가 전부 다르다(F3).
    · **분모는 명부가 아니라 채점된 사람**이다(14-1 · 9-4). 미응시·무효·중단은 판정과
      평균에서 빠지고, 그 셋을 **분해해서** 보여줘야 어디를 볼지가 나온다.
*/

// ── 공통 ────────────────────────────────────────────────────
/** 회차 흐름 · 기수 간 비교. **탭이 URL에 없다** — 들어오는 링크가 전부 기본 탭이다 */
export type AnalysisTab = 'rounds' | 'cohorts'

/** 반별 | 팀. **개인은 없다** — 개인은 이름·답변이 있어야 뜻이 생긴다(OP-04의 일) */
export type Level = 'class' | 'team'

// ── ① 회차 흐름 ─────────────────────────────────────────────
/**
 * 열 하나 = 등록된 미프 프로젝트. **8 고정이 아니다.**
 *
 * 미프 회차 수는 기수마다 6~8로 다르고(14번 · 17번), **회차를 만드는 것은 오퍼레이터**라
 * 시스템이 개수를 미리 알 방법이 없다. 8칸을 그려놓고 빈 칸을 해치로 채우면
 * *"이 기수는 8회를 한다"* 는 **없는 사실을 주장**하게 된다(OP-02 §4-2).
 */
export type RoundColumn = {
  projectId: string
  /** 셀을 열에 잇는 키. **`roundNo`로는 못 잇는다** — 프로젝트 안 번호라 전부 같다 */
  assessmentRoundId: string
  /** 기수 안 순번(`3차`의 3). 서버 `roundNo`가 아니라 **정렬 후 자리**다 */
  no: number
  /** `1차`. 열 머리 1단 */
  label: string
  /** 프로젝트명. **없으면 어느 회차인지 짚을 수 없다** — 열 머리 2단 */
  projectName: string
  /** 값이 있나. 없으면 왜 없는지가 `RoundCell.state`에 있다 */
  published: boolean
}

/** 반 하나 — **이름이 아니라 id로 고른다.** 서버 필터가 `classroomId`를 받는다 */
export type ClassOption = { classId: string; className: string }

/**
 * 셀 하나. **칸에는 값 하나**이고 분모·비교는 호버·포커스로 준다(E11).
 *
 * `sign`이 이 화면의 핵심이다 — **값이 아니라 기수 대비 부호**에 색이 붙는다.
 * 같은 회차·같은 개념을 10반이 다 보므로 **기수 전체를 빼면 난이도가 지워지고**
 * 그 반에 대해서만 말할 수 있는 것이 남는다(OP-02 §3).
 */
export type CellState =
  /** 값이 있다 */
  | 'VALUE'
  /** 진행 중이거나 마감됐지만 미발행(10-1) — **추세 계산에서도 뺀다** */
  | 'PENDING'
  /** 등록됐지만 아직 시작 안 한 회차. `집계 전`과 다른 표기이고 `0%`와도 색이 다르다 */
  | 'BEFORE'

export type Sign =
  /** 기준선보다 좋다 */
  | 'BETTER'
  /** 같다 — **중립.** 좋다·나쁘다 어느 쪽도 아니다 */
  | 'SAME'
  /** 기준선보다 나쁘다 */
  | 'WORSE'
  /** 기준선 자신. **색이 없다** — 자기 자신과 비교할 수 없다 */
  | 'BASELINE'

export type RoundCell = {
  round: number
  state: CellState
  /** 0~100. `state`가 `VALUE`일 때만 있다 */
  ratio: number | null
  risky: number | null
  /** 채점된 사람. 명부 수가 아니다 */
  graded: number | null
  sign: Sign
}

/** 판정에서 빠진 사람 3종. **총계만 쓰면 어디를 볼지가 안 나온다**(OP-02 §4-2) */
export type Uncounted = {
  /** 응시 창 안내·독촉이 도는지 — 반 운영 */
  absent: number
  /** 세션 설계나 응시 태도(9-4) */
  invalid: number
  /** 세션이 끊기는 것 — 기술 문제일 수 있다 */
  aborted: number
}

/**
 * 격자의 행. 반별이면 반, 팀이면 팀이다.
 *
 * **담당 매니저 이름을 넣지 않는다** — 반 값 옆에 사람 이름이 붙으면 **그 반의 값이
 * 그 사람 성적으로 읽힌다**(OP-02 §4-2). 누구와 이야기할지는 OP-06·OP-01이 안다.
 */
export type GridRow = {
  /** `C반` · `2팀` */
  name: string
  /** 인원. 팀 행에서 특히 필요하다 — 4명 팀은 1명이면 25%라 비율이 튄다 */
  size: number
  /** 기준선 행인가. **정렬에서 빠지고 색도 없다** */
  baseline: boolean
  cells: RoundCell[]
  uncounted: Uncounted
}

/**
 * 정렬 4종. **서로 다른 질문이다**(OP-02 §4-3).
 *
 * 전부 **정렬 키가 격자에 그대로 보인다**(E2) — 요약 열이 없어도 *"왜 이 순서인지"* 를
 * 묻지 않는다.
 */
export type RoundSort =
  /** *"지금 어디가 제일 나쁜가"* — 기본. **OP-01 반 비교에서 넘어왔을 때 그 순서와 같다** */
  | 'LATEST_WORST'
  /** *"어디가 계속 그런가"* — 키가 **붉은 칸 개수**다 */
  | 'WORSE_COUNT'
  /** *"어느 반의 값을 믿기 어려운가"* — 분모가 많이 깎인 반 */
  | 'UNCOUNTED'
  /** *"내가 아는 그 반을 찾겠다"* — 위치가 고정된다 */
  | 'NAME'

export type RoundQuery = {
  cohortId: string
  level: Level
  /**
   * 반별이면 **복수**, 팀이면 **단일**. 컨트롤 모양이 곧 규칙이다(E9·E10).
   *
   * **팀 계층에서 비어 있으면 아직 반을 안 고른 것**이다 — 시스템이 임의로 고르지
   * 않는다(어느 반인지가 그 계층 질문의 전제다).
   *
   * ⚠ **이름이 아니라 id다.** 서버 필터가 `classroomId`를 받는다.
   */
  classIds: string[]
  /**
   * 팀 계층에서 보는 **회차 하나**.
   *
   * ⚠ **팀 계층은 격자가 아니다.** 한때 팀 행 × 회차 열로 그렸는데 서버가 막는다
   * (`TEAM_LEVEL_PROJECT_REQUIRED`) — **팀은 회차마다 재편성될 수 있어** 회차를
   * 가로질러 같은 팀을 추적하는 것이 성립하지 않는다. 한 회차 안에서만 비교한다.
   */
  projectId?: string
  /**
   * 회차 범위 — **시작·끝을 직접 고른다**(프리셋으로 묶지 않는다). 다만
   * **안 보내면 서버가 정한다.**
   *
   * 정의서는 기본을 `1차 – 4차`(발행 + 진행 중)로 못 박았는데, 그건 **목업 시점
   * 데이터**(1~3차 발행) 기준이었다. 발행 회차가 둘뿐인 지금 그 상수를 그대로 쓰면
   * **표의 40%가 빈칸**이 된다 — 정의서 스스로 *"시작 전 회차를 열로 띄우면 값 없는
   * 칸이 표 폭을 먹는다"* 고 경고한 그 상태다(실측: 값 22칸 / 빈칸 22칸).
   *
   * 그래서 상수가 아니라 **규칙**으로 바꾼다: `발행된 회차 전부 + 진행 중 1개`.
   * 회차가 몇 개든, 기수가 어디까지 갔든 빈칸이 하나를 넘지 않는다.
   *
   * **판정을 서버가 한다** — 화면이 계산하려면 회차 목록을 먼저 받아야 해서 조회가
   * 두 번 나간다(api-boundary §1-②).
   */
  fromRound?: number
  toRound?: number
  sort: RoundSort
}

export type RoundGrid = {
  /** 선택 가능한 전체 회차. 범위 선택지와 `회차 등록 N회` 문구가 여기서 나온다 */
  allRounds: RoundColumn[]
  /** 범위 안의 열만. **범위 밖 회차는 열이 없다** — 색도 그 구간에서만 읽힌다 */
  columns: RoundColumn[]
  /**
   * 실제로 적용된 범위. 화면이 범위를 안 보냈으면 서버가 정한 값이 여기 온다 —
   * **툴바가 무엇을 보고 있는지 표시하려면 필요하다.**
   */
  /** 서버가 실제로 적용한 범위. **`null`이면 고를 회차가 없다** — 숫자를 지어내지 않는다 */
  appliedFrom: number | null
  appliedTo: number | null
  /**
   * 기준선 + 행들. **기준선이 계층에 따라 바뀐다**(OP-02 §3):
   * 반별이면 `기수 전체`, 팀이면 **그 반** — 팀은 같은 반 안에서 비교해야 뜻이 있다.
   */
  rows: GridRow[]
  /** 축 라벨·범례가 이 이름을 쓴다. 안 바꾸면 **무엇과 비교한 색인지** 알 수 없다 */
  baselineName: string
  /**
   * 어느 계층의 격자인가. **표가 라벨·표시를 이걸로 가른다.**
   *
   * ⚠ 전에는 표가 `baselineName === '기수'`로 계층을 알아냈는데 실제 값이 `'기수 전체'`라
   * **그 비교가 영원히 거짓**이었다 — 반별인데 머리글이 「팀」이었고 팀 전용 표시가
   * 반별에도 붙었다. 문자열로 판정하면 라벨을 바꿀 때 조용히 깨진다.
   */
  level: Level
  /**
   * 팀 계층인데 **반이나 회차를 아직 안 골랐다.** 빈 표가 아니라 **사용자가 할 일이
   * 남은 상태**라 화면이 따로 그린다 — 무엇이 빠졌는지도 같이 준다.
   */
  needs?: 'CLASS' | 'ROUND' | 'BOTH'
  /** 선택 가능한 반 전체(칩·드롭다운) */
  allClasses: ClassOption[]
}

// ── ② 기수 간 비교 ──────────────────────────────────────────
/**
 * 행 하나 = 검증 개념. **같은 교안·같은 개념만** 올라온다.
 *
 * **여기서는 절대 눈금(1~4단)이다** — 같은 것을 물었으므로 두 기수에서 값의 뜻이 같다.
 * 회차 흐름 탭이 부호를 쓰는 것과 **값의 성격이 다르다**: 저기는 회차마다 다른 것을
 * 물어서 값끼리 못 비교하고, 여기는 비교된다.
 */
/**
 * 좋아졌나 나빠졌나 — **서버가 판정한다.**
 *
 * 한때 화면이 `|diff| <= 0.2`를 임계값으로 두고 갈랐는데, 그 숫자가 어느 문서에도
 * 없어서 **화면이 기준을 만드는 것**이었다(E8). 서버가 `changeThreshold`를 갖고
 * 판정까지 해 주므로 그 자리를 없앴다.
 *
 * `NOT_COMPARABLE`은 한쪽에 그 개념이 없거나 집계 전이라 견줄 수 없다는 뜻이다 —
 * `SIMILAR`(견줬는데 비슷하다)와 다르다.
 */
export type ChangeDirection = 'WORSE' | 'SIMILAR' | 'BETTER' | 'NOT_COMPARABLE'

export type ConceptCompare = {
  conceptId: string
  conceptName: string
  /** `교안 AI_LLMOps · 4장 p.62 · 미프 3차` — 출처가 없으면 어느 개념인지 짚을 수 없다 */
  source: string
  /** 지난 기수 평균 도달(1~4). **그 기수에 없던 개념이면 null** */
  baseAvg: number | null
  /**
   * 이번 기수 평균 도달.
   *
   * ⚠ **`null`이 될 수 있다.** 집계 전이거나 이번 기수에 없는 개념일 때다
   * (`target.presence`가 `ABSENT_IN_COHORT`). 한때 필수였는데 서버가 두 쪽 모두
   * 없을 수 있다고 준다 — 0으로 채우면 *"평균 0단"* 이라는 없는 사실이 된다.
   */
  currentAvg: number | null
  /**
   * 교안 버전. *"교안을 고친 것이 효과가 있었나"* 가 이 표의 핵심 질문이고
   * 버전이 없으면 답할 수 없다.
   */
  baseVersion: string | null
  currentVersion: string | null
  /** 서버 판정. 화면은 이 값으로 문구·색만 고른다 */
  direction: ChangeDirection
  /** 도달 단계 차이. `NOT_COMPARABLE`이면 `null` */
  delta: number | null
}

export type CohortSort = 'WORSENED' | 'CONCEPT_NAME'

export type CohortQuery = {
  cohortId: string
  /** 비교 대상 기수. 없으면 서버가 고른다 */
  compareCohortId: string | null
  sort: CohortSort
}

export type CohortCompare = {
  /**
   * 서버가 **실제로** 같은 교안 필터를 걸었나.
   *
   * ⚠ 화면은 `true`를 보내는데 **응답이 늘 `false`로 온다**(실측 2026-08-12 ·
   * op-02-situations §2-2). 필터가 안 도는 것인지 필드만 안 채워진 것인지 지금
   * 데이터로는 못 가른다 — 그래서 **화면이 단언을 낮춘다.** 표가 *"같은 교안 ·
   * 같은 개념"* 이라고 말하려면 서버가 그렇다고 해야 한다.
   */
  sameCurriculumOnly: boolean
  /**
   * 비교 가능한 기수 목록. **비어 있으면 첫 기수**다 — 다른 기관 평균을 만들지 않는다.
   *
   * 서버는 비교 불가한 기수도 `comparable: false`로 함께 준다(교안이 하나도 안 겹치는
   * 기수). **그것까지 목록에 두고 고를 수 없게 한다** — 빼 버리면 *"왜 저 기수는
   * 목록에 없지"* 가 되고, 답은 "겹치는 교안이 없어서"라 사용자가 알아야 할 사실이다.
   */
  availableCohorts: { id: string; label: string; comparable: boolean }[]
  /** 실제로 견준 기수의 id. **사용자가 안 골랐으면 서버 목록의 첫 `comparable`** 이다 */
  compareCohortId: string | null
  compareCohortLabel: string | null
  currentCohortLabel: string
  rows: ConceptCompare[]
}

